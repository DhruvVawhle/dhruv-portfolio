/**
 * Returns the official website URL for a given technology name.
 * Uses exact lookup first, then normalizes common versions/suffixes.
 */
export function getTechWebsite(name: string): string {
  if (!name) return "https://github.com";

  const trimmed = name.trim();
  if (TECH_URLS[trimmed]) return TECH_URLS[trimmed];

  // Case-insensitive match
  const lower = trimmed.toLowerCase();
  for (const [key, url] of Object.entries(TECH_URLS)) {
    if (key.toLowerCase() === lower) return url;
  }

  // Version stripping heuristics (e.g. "Next.js 16" -> "Next.js", "Python 3.11" -> "Python")
  const strippedVersion = trimmed.replace(/\s+(v?\d+(\.\d+)*)$/i, "");
  if (TECH_URLS[strippedVersion]) return TECH_URLS[strippedVersion];

  // Common prefix heuristics
  if (lower.startsWith("next")) return TECH_URLS["Next.js"];
  if (lower.startsWith("react three") || lower.startsWith("three")) return TECH_URLS["Three.js"];
  if (lower.startsWith("react")) return TECH_URLS["React"];
  if (lower.startsWith("tailwind")) return TECH_URLS["Tailwind CSS"];
  if (lower.startsWith("fastapi")) return TECH_URLS["FastAPI"];
  if (lower.startsWith("firebase")) return TECH_URLS["Firebase"];
  if (lower.startsWith("firestore")) return TECH_URLS["Cloud Firestore"];
  if (lower.startsWith("groq")) return TECH_URLS["Groq LPU"];
  if (lower.startsWith("faiss")) return TECH_URLS["FAISS"];
  if (lower.startsWith("sqlite")) return TECH_URLS["SQLite"];
  if (lower.startsWith("redis") || lower.includes("redis")) return TECH_URLS["Upstash Redis"];
  if (lower.startsWith("pytorch") || lower.startsWith("torch")) return TECH_URLS["PyTorch"];
  if (lower.startsWith("gemini")) return TECH_URLS["Google Gemini API"];
  if (lower.startsWith("lenis")) return TECH_URLS["Lenis"];

  // Fallback to Wikipedia / Devdocs search
  return `https://en.wikipedia.org/wiki/Special:Search?search=${encodeURIComponent(trimmed)}`;
}
